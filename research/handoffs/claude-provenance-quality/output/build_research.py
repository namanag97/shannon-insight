def applicability_decision(lib: str, mid: str) -> tuple[str, str, list]:
    kind = MODULE_BY_ID[mid]["module_kind"]
    lpe = lib.startswith("library.lpe.")
    if kind == L:
        if LOCAL_APPLY.get(lib) == mid:
            return "APPLIES_WITH_REFINEMENT", "Local residual for this library's changed boundary.", [mid]
        return "NOT_APPLICABLE", "Local refinement belongs to a different library.", []
    if mid.startswith("module.lpe.") and not lpe:
        return "NOT_APPLICABLE", "LPE family-axis module was considered and rejected for this QOR library.", []
    if mid.startswith("module.qor.") and lpe:
        return "NOT_APPLICABLE", "QOR family-axis module was considered and rejected for this LPE library.", []
