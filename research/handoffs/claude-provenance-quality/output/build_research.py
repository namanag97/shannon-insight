def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def dump_jsonl(path: Path, rows: list[dict], key) -> None:
    def k(row: dict):
        if isinstance(key, tuple):
            return tuple(str(row.get(x, "")) for x in key)
        return str(row.get(key, ""))

    rows = sorted(rows, key=k)
    text = "".join(
        json.dumps(r, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n" for r in rows
    )
    path.write_text(text, encoding="utf-8")


def digest_text(*parts: str) -> str:
    return sha256_bytes("\n".join(parts).encode("utf-8"))


def snapshot() -> dict:
    files = []
    for rel in SNAPSHOT_INPUTS:
        p = REPO / rel
        data = p.read_bytes() if p.exists() else b""
        nrec = None
        if rel.endswith(".jsonl") and p.exists():
            nrec = sum(1 for line in data.splitlines() if line.strip())
        files.append(
            {
                "path": rel,
                "sha256": sha256_bytes(data),
                "bytes": len(data),
                "record_count": nrec,
                "exists": p.exists(),
            }
        )
    aggregate = sha256_bytes("".join(f["sha256"] for f in files).encode("utf-8"))
    return {"files": files, "aggregate_digest": aggregate}


def assigned_refs() -> list[str]:
    refs = []
    path = REPO / "research/domain_atlas/compiler/library_registry/exact_api_closure/research-batches.jsonl"
    for line in path.read_text(encoding="utf-8").splitlines():
        rec = json.loads(line)
        if rec.get("research_family") in FAMILIES:
            refs.extend(rec["library_refs"])
    return refs


def src(**kwargs) -> dict:
    claims = kwargs["bounded_claims_supported"]
    kwargs.setdefault("accessed_on", ACCESSED)
    kwargs.setdefault("supersedes_source_refs", [])
    kwargs.setdefault("contradicts_source_refs", [])
    kwargs.setdefault(
        "content_digest",
        digest_text(kwargs["source_id"], kwargs["uri"], json.dumps(claims, sort_keys=True)),
    )
    return kwargs


def module(**kwargs) -> dict:
    kwargs.setdefault("status", "CANDIDATE_UNRATIFIED")
    kwargs.setdefault("dependent_module_refs", [])
    kwargs.setdefault("conflicts", [])
    return kwargs


def neigh(neighbor: str, relation: str) -> dict:
    return {"neighbor": neighbor, "relation": relation}


